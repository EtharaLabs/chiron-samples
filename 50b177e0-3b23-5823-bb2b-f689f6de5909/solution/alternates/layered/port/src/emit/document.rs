///                                  yyjson_write_err *err)`
/// yyjson.c:10457
#[unsafe(no_mangle)]
pub unsafe extern "C" fn yyjson_mut_val_write_buf(buf: *mut c_char,
                                                  buf_len: usize,
                                                  val: *const yyjson_mut_val,
                                                  flg: yyjson_write_flag,
                                                  err: *mut yyjson_write_err)
    -> usize {
    unsafe {
        if buf.is_null() || buf_len == 0 {
            if !err.is_null() {
                (*err).code = YYJSON_WRITE_ERROR_INVALID_PARAMETER;
            }
            if !err.is_null() {
                (*err).msg = c"input buf or buf_len is invalid".as_ptr();
            }
            0
        } else {
            let mut buf_len: usize = buf_len;
            let mut null_alc: yyjson_alc = YYJSON_NULL_ALC;
            mut_write_root(val as *mut yyjson_mut_val, 0, flg,
                           &raw mut null_alc, buf as *mut u8,
                           &raw mut buf_len, err);
            buf_len
        }
    }
}


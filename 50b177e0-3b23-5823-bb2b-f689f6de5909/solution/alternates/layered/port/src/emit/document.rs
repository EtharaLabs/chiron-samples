#[repr(C)]
pub(crate) struct yyjson_write_ctx {
    pub tag: usize,
}

const _: () = assert!(core::mem::size_of::<yyjson_write_ctx>() == 8);

#[inline(always)]
pub(crate) unsafe fn yyjson_write_ctx_set(ctx: *mut yyjson_write_ctx,
                                          size: usize, is_obj: bool) {
    unsafe {
        (*ctx).tag = size.wrapping_shl(1) | (is_obj as usize);
    }
}

#[inline(always)]
pub(crate) unsafe fn yyjson_write_ctx_get(ctx: *mut yyjson_write_ctx,
                                          size: *mut usize,
                                          is_obj: *mut bool) {
    unsafe {
        let tag: usize = (*ctx).tag;
        *size = tag >> 1;
        *is_obj = (tag & 1) != 0;
    }
}

/* The `goto` labels of the writers' value loops, as explicit states. */
const S_VAL_BEGIN: u32 = 0;
const S_VAL_END: u32 = 1;
const S_CTN_END: u32 = 2;

/** Write single JSON value. */
#[inline(always)]
pub(crate) unsafe fn emit_root_single(val: *mut yyjson_val,
                                       flg: yyjson_write_flag,
                                       alc: yyjson_alc,
                                       buf: *mut u8,
                                       dat_len: *mut usize,
                                       err: *mut yyjson_write_err) -> *mut u8 {
    unsafe {
        let mut hdr: *mut u8 = ptr::null_mut();
        let mut cur: *mut u8;
        let str_len: usize;
        let str_ptr: *mut u8;
        let enc_table: *const char_enc_type = get_enc_table_with_flag(flg);
        let hex_table: *const u8 = get_hex_table_with_flag(flg);
        let cpy: bool = enc_table == enc_table_cpy.as_ptr();
        let esc: bool = writer_flag_set(flg, YYJSON_WRITE_ESCAPE_UNICODE, false);
        let inv: bool = writer_flag_set(flg, YYJSON_WRITE_ALLOW_INVALID_UNICODE,
                                  true);
        let newline: bool = writer_flag_set(flg, YYJSON_WRITE_NEWLINE_AT_END, false);
        let end_len: usize = 2; /* '\n' and '\0' */

        let fail_code: yyjson_write_code;
        let fail_msg: *const c_char;

        /* #define incr_len(_len) do { \
               if (buf) hdr = *dat_len >= _len ? (u8 *)buf : (u8 *)NULL; \
               else hdr = (u8 *)alc.malloc(alc.ctx, _len); \
               if (!hdr) goto fail_alloc; \
               cur = hdr; \
           } while (false) */
        macro_rules! incr_len {
            ($len:expr, $f:lifetime) => {{
                let _len: usize = $len;
                if !buf.is_null() {
                    hdr = if *dat_len >= _len { buf } else { ptr::null_mut() };
                } else {
                    hdr = (alc.malloc.unwrap_unchecked())(alc.ctx, _len)
                        as *mut u8;
                }
                if hdr.is_null() {
                    /* goto fail_alloc */
                    fail_code = YYJSON_WRITE_ERROR_MEMORY_ALLOCATION;
                    fail_msg = MSG_MALLOC;
                    break $f;
                }
                cur = hdr;
            }};
        }

        /* `check_str_len(_len)` is `(sizeof(usize) < 8) && ...`, i.e. dead
           on LP64, so it expands to nothing here. */

        'fail: {
            match raw_doc_get_type(val as *mut c_void) {
                YYJSON_TYPE_RAW => {
                    str_len = raw_doc_get_span(val as *mut c_void);
                    str_ptr = raw_doc_get_str(val as *mut c_void)
                        as *mut u8;
                    incr_len!(str_len.wrapping_add(end_len), 'fail);
                    cur = emit_raw(cur, str_ptr, str_len);
                }
                YYJSON_TYPE_STR => {
                    str_len = raw_doc_get_span(val as *mut c_void);
                    str_ptr = raw_doc_get_str(val as *mut c_void)
                        as *mut u8;
                    incr_len!(str_len.wrapping_mul(6).wrapping_add(2)
                                  .wrapping_add(end_len), 'fail);
                    if cpy
                        && raw_doc_get_subtype(val as *mut c_void) != 0 {
                        cur = emit_str_noesc(cur, str_ptr, str_len);
                    } else {
                        cur = emit_str(cur, esc, inv, str_ptr, str_len,
                                        enc_table, hex_table);
                        if cur.is_null() {
                            /* goto fail_str */
                            fail_code = YYJSON_WRITE_ERROR_INVALID_STRING;
                            fail_msg = MSG_ERR_UTF8;
                            break 'fail;
                        }
                    }
                }
                YYJSON_TYPE_NUM => {
                    incr_len!(FP_BUF_LEN.wrapping_add(end_len), 'fail);
                    cur = write_num(cur, val, flg);
                    if cur.is_null() {
                        /* goto fail_num */
                        fail_code = YYJSON_WRITE_ERROR_NAN_OR_INF;
                        fail_msg = MSG_NAN_INF;
                        break 'fail;
                    }
                }
                YYJSON_TYPE_BOOL => {
                    incr_len!(8, 'fail);
                    cur = emit_bool(cur,
                                     raw_doc_get_bool(val
                                         as *mut c_void));
                }
                YYJSON_TYPE_NULL => {
                    incr_len!(8, 'fail);
                    cur = emit_null(cur);
                }
                YYJSON_TYPE_ARR => {
                    incr_len!(2usize.wrapping_add(end_len), 'fail);
                    copy_octets_2(cur as *mut c_void,
                                b"[]".as_ptr() as *const c_void);
                    cur = cur.add(2);
                }
                YYJSON_TYPE_OBJ => {
                    incr_len!(2usize.wrapping_add(end_len), 'fail);
                    copy_octets_2(cur as *mut c_void,
                                b"{}".as_ptr() as *const c_void);
                    cur = cur.add(2);
                }
                _ => {
                    /* goto fail_type */
                    fail_code = YYJSON_WRITE_ERROR_INVALID_VALUE_TYPE;
                    fail_msg = MSG_ERR_TYPE;
                    break 'fail;
                }
            }

            if newline {
                *cur = b'\n';
                cur = cur.add(1);
            }
            *cur = b'\0';
            *dat_len = cur.offset_from(hdr) as usize;
            ffi::memset(err as *mut c_void, 0,
                        core::mem::size_of::<yyjson_write_err>());
            return hdr;
        }

        /* return_err(_code, _msg) */
        if !hdr.is_null() {
            (alc.free.unwrap_unchecked())(alc.ctx, hdr as *mut c_void);
        }
        *dat_len = 0;
        (*err).code = fail_code;
        (*err).msg = fail_msg;
        ptr::null_mut()
    }
}

/** Write JSON document minify.
    The root of this document should be a non-empty container. */
#[inline(always)]
pub(crate) unsafe fn emit_root_minify(root: *mut yyjson_val,
                                       flg: yyjson_write_flag,
                                       alc: yyjson_alc,
                                       buf: *mut u8,
                                       dat_len: *mut usize,
                                       err: *mut yyjson_write_err) -> *mut u8 {
    unsafe {
        let mut val: *mut yyjson_val;
        let mut val_type: yyjson_type;
        let mut ctn_len: usize;
        let mut ctn_len_tmp: usize;
        let mut ctn_obj: bool;
        let mut ctn_obj_tmp: bool;
        let mut is_key: bool;
        let mut hdr: *mut u8;
        let mut cur: *mut u8;
        let mut end: *mut u8;
        let mut tmp: *mut u8;
        let mut ctx: *mut yyjson_write_ctx;
        let mut ctx_tmp: *mut yyjson_write_ctx;
        let mut alc_len: usize;
        let mut alc_inc: usize;
        let mut ctx_len: usize;
        let mut ext_len: usize;
        let mut str_len: usize;
        let mut str_ptr: *mut u8;
        let enc_table: *const char_enc_type = get_enc_table_with_flag(flg);
        let hex_table: *const u8 = get_hex_table_with_flag(flg);
        let cpy: bool = enc_table == enc_table_cpy.as_ptr();
        let esc: bool = writer_flag_set(flg, YYJSON_WRITE_ESCAPE_UNICODE, false);
        let inv: bool = writer_flag_set(flg, YYJSON_WRITE_ALLOW_INVALID_UNICODE,
                                  true);
        let newline: bool = writer_flag_set(flg, YYJSON_WRITE_NEWLINE_AT_END, false);

        let fail_code: yyjson_write_code;
        let fail_msg: *const c_char;

        const SZ_CTX: usize = core::mem::size_of::<yyjson_write_ctx>();

        /* #define incr_len(_len) ... (the growth step; the
           `(sizeof(usize) < 8) && size_add_is_overflow(...)` guard is dead
           on LP64 and so is omitted) */
        macro_rules! incr_len {
            ($len:expr, $f:lifetime) => {{
                ext_len = $len as usize;
                if (cur as usize).wrapping_add(ext_len) >= ctx as usize {
                    let ctx_pos: usize =
                        (ctx as usize).wrapping_sub(hdr as usize);
                    let cur_pos: usize =
                        (cur as usize).wrapping_sub(hdr as usize);
                    ctx_len = (end as usize).wrapping_sub(ctx as usize);
                    alc_inc = yyjson_max(alc_len / 2, ext_len);
                    alc_inc = size_align_up(alc_inc, SZ_CTX);
                    alc_len = alc_len.wrapping_add(alc_inc);
                    tmp = (alc.realloc.unwrap_unchecked())(
                        alc.ctx, hdr as *mut c_void,
                        alc_len.wrapping_sub(alc_inc), alc_len) as *mut u8;
                    if tmp.is_null() {
                        /* goto fail_alloc */
                        fail_code = YYJSON_WRITE_ERROR_MEMORY_ALLOCATION;
                        fail_msg = MSG_MALLOC;
                        break $f;
                    }
                    ctx_tmp = tmp.add(alc_len.wrapping_sub(ctx_len))
                        as *mut yyjson_write_ctx;
                    ffi::memmove(ctx_tmp as *mut c_void,
                                 tmp.add(ctx_pos) as *const c_void, ctx_len);
                    /* The `ctx` and `end` stores are dead in the last
                       expansion (the one in `doc_end`); the C macro performs
                       them unconditionally, so they are kept here. */
                    #[allow(unused_assignments)]
                    {
                        ctx = ctx_tmp;
                        end = tmp.add(alc_len);
                    }
                    cur = tmp.add(cur_pos);
                    hdr = tmp;
                }
            }};
        }

        'fail: {
            if !buf.is_null() {
                hdr = buf;
                alc_len = *dat_len;
                alc_len = size_align_down(alc_len, SZ_CTX);
                if alc_len <= SZ_CTX {
                    /* goto fail_alloc */
                    fail_code = YYJSON_WRITE_ERROR_MEMORY_ALLOCATION;
                    fail_msg = MSG_MALLOC;
                    break 'fail;
                }
            } else {
                alc_len = (*root).uni.ofs
                    / core::mem::size_of::<yyjson_val>();
                alc_len = alc_len
                    .wrapping_mul(YYJSON_WRITER_ESTIMATED_MINIFY_RATIO)
                    .wrapping_add(64);
                alc_len = size_align_up(alc_len, SZ_CTX);
                hdr = (alc.malloc.unwrap_unchecked())(alc.ctx, alc_len)
                    as *mut u8;
                if hdr.is_null() {
                    /* goto fail_alloc */
                    fail_code = YYJSON_WRITE_ERROR_MEMORY_ALLOCATION;
                    fail_msg = MSG_MALLOC;
                    break 'fail;
                }
            }
            cur = hdr;
            end = hdr.add(alc_len);
            ctx = end as *mut yyjson_write_ctx;

            /* doc_begin: */
            val = root;
            val_type = raw_doc_get_type(val as *mut c_void);
            ctn_obj = val_type == YYJSON_TYPE_OBJ;
            ctn_len = raw_doc_get_span(val as *mut c_void)
                .wrapping_shl(ctn_obj as u32);
            *cur = b'[' | ((ctn_obj as u8) << 5);
            cur = cur.add(1);
            val = val.add(1);

            let mut state: u32 = S_VAL_BEGIN;
            loop {
                if state == S_VAL_BEGIN {
                    /* val_begin: */
                    val_type = raw_doc_get_type(val as *mut c_void);
                    if val_type == YYJSON_TYPE_STR {
                        is_key = ((ctn_obj as u8) & (!ctn_len) as u8) != 0;
                        str_len = raw_doc_get_span(val as *mut c_void);
                        str_ptr = raw_doc_get_str(val as *mut c_void)
                            as *mut u8;
                        incr_len!(str_len.wrapping_mul(6).wrapping_add(16),
                                  'fail);
                        if cpy && raw_doc_get_subtype(val as *mut c_void)
                            != 0 {
                            cur = emit_str_noesc(cur, str_ptr, str_len);
                        } else {
                            cur = emit_str(cur, esc, inv, str_ptr, str_len,
                                            enc_table, hex_table);
                            if cur.is_null() {
                                /* goto fail_str */
                                fail_code = YYJSON_WRITE_ERROR_INVALID_STRING;
                                fail_msg = MSG_ERR_UTF8;
                                break 'fail;
                            }
                        }
                        *cur = if is_key { b':' } else { b',' };
                        cur = cur.add(1);
                        state = S_VAL_END;
                        continue;
                    }
                    if val_type == YYJSON_TYPE_NUM {
                        incr_len!(FP_BUF_LEN, 'fail);
                        cur = write_num(cur, val, flg);
                        if cur.is_null() {
                            /* goto fail_num */
                            fail_code = YYJSON_WRITE_ERROR_NAN_OR_INF;
                            fail_msg = MSG_NAN_INF;
                            break 'fail;
                        }
                        *cur = b',';
                        cur = cur.add(1);
                        state = S_VAL_END;
                        continue;
                    }
                    if (val_type & (YYJSON_TYPE_ARR & YYJSON_TYPE_OBJ))
                        == (YYJSON_TYPE_ARR & YYJSON_TYPE_OBJ) {
                        ctn_len_tmp = raw_doc_get_span(val as *mut c_void);
                        ctn_obj_tmp = val_type == YYJSON_TYPE_OBJ;
                        incr_len!(2usize.wrapping_mul(SZ_CTX), 'fail);
                        if ctn_len_tmp == 0 {
                            /* write empty container */
                            *cur = b'[' | ((ctn_obj_tmp as u8) << 5);
                            cur = cur.add(1);
                            *cur = b']' | ((ctn_obj_tmp as u8) << 5);
                            cur = cur.add(1);
                            *cur = b',';
                            cur = cur.add(1);
                            state = S_VAL_END;
                            continue;
                        } else {
                            /* push context, setup new container */
                            ctx = ctx.sub(1);
                            yyjson_write_ctx_set(ctx, ctn_len, ctn_obj);
                            ctn_len = ctn_len_tmp
                                .wrapping_shl(ctn_obj_tmp as u32);
                            ctn_obj = ctn_obj_tmp;
                            *cur = b'[' | ((ctn_obj as u8) << 5);
                            cur = cur.add(1);
                            val = val.add(1);
                            state = S_VAL_BEGIN;
                            continue;
                        }
                    }
                    if val_type == YYJSON_TYPE_BOOL {
                        incr_len!(16, 'fail);
                        cur = emit_bool(cur, raw_doc_get_bool(
                            val as *mut c_void));
                        cur = cur.add(1);
                        state = S_VAL_END;
                        continue;
                    }
                    if val_type == YYJSON_TYPE_NULL {
                        incr_len!(16, 'fail);
                        cur = emit_null(cur);
                        cur = cur.add(1);
                        state = S_VAL_END;
                        continue;
                    }
                    if val_type == YYJSON_TYPE_RAW {
                        str_len = raw_doc_get_span(val as *mut c_void);
                        str_ptr = raw_doc_get_str(val as *mut c_void)
                            as *mut u8;
                        incr_len!(str_len.wrapping_add(2), 'fail);
                        cur = emit_raw(cur, str_ptr, str_len);
                        *cur = b',';
                        cur = cur.add(1);
                        state = S_VAL_END;
                        continue;
                    }
                    /* goto fail_type */
                    fail_code = YYJSON_WRITE_ERROR_INVALID_VALUE_TYPE;
                    fail_msg = MSG_ERR_TYPE;
                    break 'fail;
                }
                if state == S_VAL_END {
                    /* val_end: */
                    val = val.add(1);
                    ctn_len = ctn_len.wrapping_sub(1);
                    if ctn_len == 0 {
                        state = S_CTN_END;
                        continue;
                    }
                    state = S_VAL_BEGIN;
                    continue;
                }
                /* ctn_end: */
                cur = cur.sub(1);
                *cur = b']' | ((ctn_obj as u8) << 5);
                cur = cur.add(1);
                *cur = b',';
                cur = cur.add(1);
                if ctx as *mut u8 >= end {
                    break; /* goto doc_end */
                }
                yyjson_write_ctx_get(ctx, &raw mut ctn_len,
                                     &raw mut ctn_obj);
                ctx = ctx.add(1);
                ctn_len = ctn_len.wrapping_sub(1);
                if ctn_len > 0 {
                    state = S_VAL_BEGIN;
                } else {
                    state = S_CTN_END;
                }
                continue;
            }

            /* doc_end: */
            if newline {
                incr_len!(2, 'fail);
                *cur.sub(1) = b'\n';
                cur = cur.add(1);
            }
            cur = cur.sub(1);
            *cur = b'\0';
            *dat_len = cur.offset_from(hdr) as usize;
            ffi::memset(err as *mut c_void, 0,
                        core::mem::size_of::<yyjson_write_err>());
            return hdr;
        }

        /* return_err(_code, _msg) */
        *dat_len = 0;
        (*err).code = fail_code;
        (*err).msg = fail_msg;
        if !hdr.is_null() {
            (alc.free.unwrap_unchecked())(alc.ctx, hdr as *mut c_void);
        }
        ptr::null_mut()
    }
}

/** Write JSON document pretty.
    The root of this document should be a non-empty container. */
#[inline(always)]
pub(crate) unsafe fn emit_root_pretty(root: *mut yyjson_val,
                                       flg: yyjson_write_flag,
                                       alc: yyjson_alc,
                                       buf: *mut u8,
                                       dat_len: *mut usize,
                                       err: *mut yyjson_write_err) -> *mut u8 {
    unsafe {
        let mut val: *mut yyjson_val;
        let mut val_type: yyjson_type;
        let mut ctn_len: usize;
        let mut ctn_len_tmp: usize;
        let mut ctn_obj: bool;
        let mut ctn_obj_tmp: bool;
        let mut is_key: bool;
        let mut no_indent: bool;
        let mut hdr: *mut u8;
        let mut cur: *mut u8;
        let mut end: *mut u8;
        let mut tmp: *mut u8;
        let mut ctx: *mut yyjson_write_ctx;
        let mut ctx_tmp: *mut yyjson_write_ctx;
        let mut alc_len: usize;
        let mut alc_inc: usize;
        let mut ctx_len: usize;
        let mut ext_len: usize;
        let mut str_len: usize;
        let mut level: usize;
        let mut str_ptr: *mut u8;
        let enc_table: *const char_enc_type = get_enc_table_with_flag(flg);
        let hex_table: *const u8 = get_hex_table_with_flag(flg);
        let cpy: bool = enc_table == enc_table_cpy.as_ptr();
        let esc: bool = writer_flag_set(flg, YYJSON_WRITE_ESCAPE_UNICODE, false);
        let inv: bool = writer_flag_set(flg, YYJSON_WRITE_ALLOW_INVALID_UNICODE,
                                  true);
        let spaces: usize =
            if writer_flag_set(flg, YYJSON_WRITE_PRETTY_TWO_SPACES, false) {
                2
            } else {
                4
            };
        let newline: bool = writer_flag_set(flg, YYJSON_WRITE_NEWLINE_AT_END, false);

        let fail_code: yyjson_write_code;
        let fail_msg: *const c_char;

        const SZ_CTX: usize = core::mem::size_of::<yyjson_write_ctx>();

        macro_rules! incr_len {
            ($len:expr, $f:lifetime) => {{
                ext_len = $len as usize;
                if (cur as usize).wrapping_add(ext_len) >= ctx as usize {
                    let ctx_pos: usize =
                        (ctx as usize).wrapping_sub(hdr as usize);
                    let cur_pos: usize =
                        (cur as usize).wrapping_sub(hdr as usize);
                    ctx_len = (end as usize).wrapping_sub(ctx as usize);
                    alc_inc = yyjson_max(alc_len / 2, ext_len);
                    alc_inc = size_align_up(alc_inc, SZ_CTX);
                    alc_len = alc_len.wrapping_add(alc_inc);
                    tmp = (alc.realloc.unwrap_unchecked())(
                        alc.ctx, hdr as *mut c_void,
                        alc_len.wrapping_sub(alc_inc), alc_len) as *mut u8;
                    if tmp.is_null() {
                        /* goto fail_alloc */
                        fail_code = YYJSON_WRITE_ERROR_MEMORY_ALLOCATION;
                        fail_msg = MSG_MALLOC;
                        break $f;
                    }
                    ctx_tmp = tmp.add(alc_len.wrapping_sub(ctx_len))
                        as *mut yyjson_write_ctx;
                    ffi::memmove(ctx_tmp as *mut c_void,
                                 tmp.add(ctx_pos) as *const c_void, ctx_len);
                    /* The `ctx` and `end` stores are dead in the last
                       expansion (the one in `doc_end`); the C macro performs
                       them unconditionally, so they are kept here. */
                    #[allow(unused_assignments)]
                    {
                        ctx = ctx_tmp;
                        end = tmp.add(alc_len);
                    }
                    cur = tmp.add(cur_pos);
                    hdr = tmp;
                }
            }};
        }

        'fail: {
            if !buf.is_null() {
                hdr = buf;
                alc_len = *dat_len;
                alc_len = size_align_down(alc_len, SZ_CTX);
                if alc_len <= SZ_CTX {
                    fail_code = YYJSON_WRITE_ERROR_MEMORY_ALLOCATION;
                    fail_msg = MSG_MALLOC;
                    break 'fail;
                }
            } else {
                alc_len = (*root).uni.ofs
                    / core::mem::size_of::<yyjson_val>();
                alc_len = alc_len
                    .wrapping_mul(YYJSON_WRITER_ESTIMATED_PRETTY_RATIO)
                    .wrapping_add(64);
                alc_len = size_align_up(alc_len, SZ_CTX);
                hdr = (alc.malloc.unwrap_unchecked())(alc.ctx, alc_len)
                    as *mut u8;
                if hdr.is_null() {
                    fail_code = YYJSON_WRITE_ERROR_MEMORY_ALLOCATION;
                    fail_msg = MSG_MALLOC;
                    break 'fail;
                }
            }
            cur = hdr;
            end = hdr.add(alc_len);
            ctx = end as *mut yyjson_write_ctx;

            /* doc_begin: */
            val = root;
            val_type = raw_doc_get_type(val as *mut c_void);
            ctn_obj = val_type == YYJSON_TYPE_OBJ;
            ctn_len = raw_doc_get_span(val as *mut c_void)
                .wrapping_shl(ctn_obj as u32);
            *cur = b'[' | ((ctn_obj as u8) << 5);
            cur = cur.add(1);
            *cur = b'\n';
            cur = cur.add(1);
            val = val.add(1);
            level = 1;

            let mut state: u32 = S_VAL_BEGIN;
            loop {
                if state == S_VAL_BEGIN {
                    /* val_begin: */
                    val_type = raw_doc_get_type(val as *mut c_void);
                    if val_type == YYJSON_TYPE_STR {
                        is_key = ((ctn_obj as u8) & (!ctn_len) as u8) != 0;
                        no_indent = ((ctn_obj as u8) & (ctn_len as u8)) != 0;
                        str_len = raw_doc_get_span(val as *mut c_void);
                        str_ptr = raw_doc_get_str(val as *mut c_void)
                            as *mut u8;
                        incr_len!(str_len.wrapping_mul(6).wrapping_add(16)
                                      .wrapping_add(if no_indent {
                                          0
                                      } else {
                                          level.wrapping_mul(4)
                                      }), 'fail);
                        cur = emit_indent(cur, if no_indent { 0 } else { level },
                                           spaces);
                        if cpy && raw_doc_get_subtype(val as *mut c_void)
                            != 0 {
                            cur = emit_str_noesc(cur, str_ptr, str_len);
                        } else {
                            cur = emit_str(cur, esc, inv, str_ptr, str_len,
                                            enc_table, hex_table);
                            if cur.is_null() {
                                fail_code = YYJSON_WRITE_ERROR_INVALID_STRING;
                                fail_msg = MSG_ERR_UTF8;
                                break 'fail;
                            }
                        }
                        *cur = if is_key { b':' } else { b',' };
                        cur = cur.add(1);
                        *cur = if is_key { b' ' } else { b'\n' };
                        cur = cur.add(1);
                        state = S_VAL_END;
                        continue;
                    }
                    if val_type == YYJSON_TYPE_NUM {
                        no_indent = ((ctn_obj as u8) & (ctn_len as u8)) != 0;
                        incr_len!(FP_BUF_LEN.wrapping_add(if no_indent {
                            0
                        } else {
                            level.wrapping_mul(4)
                        }), 'fail);
                        cur = emit_indent(cur, if no_indent { 0 } else { level },
                                           spaces);
                        cur = write_num(cur, val, flg);
                        if cur.is_null() {
                            fail_code = YYJSON_WRITE_ERROR_NAN_OR_INF;
                            fail_msg = MSG_NAN_INF;
                            break 'fail;
                        }
                        *cur = b',';
                        cur = cur.add(1);
                        *cur = b'\n';
                        cur = cur.add(1);
                        state = S_VAL_END;
                        continue;
                    }
                    if (val_type & (YYJSON_TYPE_ARR & YYJSON_TYPE_OBJ))
                        == (YYJSON_TYPE_ARR & YYJSON_TYPE_OBJ) {
                        no_indent = ((ctn_obj as u8) & (ctn_len as u8)) != 0;
                        ctn_len_tmp = raw_doc_get_span(val as *mut c_void);
                        ctn_obj_tmp = val_type == YYJSON_TYPE_OBJ;
                        incr_len!(2usize.wrapping_mul(SZ_CTX)
                                      .wrapping_add(if no_indent {
                                          0
                                      } else {
                                          level.wrapping_mul(4)
                                      }), 'fail);
                        if ctn_len_tmp == 0 {
                            /* write empty container */
                            cur = emit_indent(cur,
                                               if no_indent { 0 } else { level },
                                               spaces);
                            *cur = b'[' | ((ctn_obj_tmp as u8) << 5);
                            cur = cur.add(1);
                            *cur = b']' | ((ctn_obj_tmp as u8) << 5);
                            cur = cur.add(1);
                            *cur = b',';
                            cur = cur.add(1);
                            *cur = b'\n';
                            cur = cur.add(1);
                            state = S_VAL_END;
                            continue;
                        } else {
                            /* push context, setup new container */
                            ctx = ctx.sub(1);
                            yyjson_write_ctx_set(ctx, ctn_len, ctn_obj);
                            ctn_len = ctn_len_tmp
                                .wrapping_shl(ctn_obj_tmp as u32);
                            ctn_obj = ctn_obj_tmp;
                            cur = emit_indent(cur,
                                               if no_indent { 0 } else { level },
                                               spaces);
                            level = level.wrapping_add(1);
                            *cur = b'[' | ((ctn_obj as u8) << 5);
                            cur = cur.add(1);
                            *cur = b'\n';
                            cur = cur.add(1);
                            val = val.add(1);
                            state = S_VAL_BEGIN;
                            continue;
                        }
                    }
                    if val_type == YYJSON_TYPE_BOOL {
                        no_indent = ((ctn_obj as u8) & (ctn_len as u8)) != 0;
                        incr_len!(16usize.wrapping_add(if no_indent {
                            0
                        } else {
                            level.wrapping_mul(4)
                        }), 'fail);
                        cur = emit_indent(cur, if no_indent { 0 } else { level },
                                           spaces);
                        cur = emit_bool(cur, raw_doc_get_bool(
                            val as *mut c_void));
                        cur = cur.add(2);
                        state = S_VAL_END;
                        continue;
                    }
                    if val_type == YYJSON_TYPE_NULL {
                        no_indent = ((ctn_obj as u8) & (ctn_len as u8)) != 0;
                        incr_len!(16usize.wrapping_add(if no_indent {
                            0
                        } else {
                            level.wrapping_mul(4)
                        }), 'fail);
                        cur = emit_indent(cur, if no_indent { 0 } else { level },
                                           spaces);
                        cur = emit_null(cur);
                        cur = cur.add(2);
                        state = S_VAL_END;
                        continue;
                    }
                    if val_type == YYJSON_TYPE_RAW {
                        no_indent = ((ctn_obj as u8) & (ctn_len as u8)) != 0;
                        str_len = raw_doc_get_span(val as *mut c_void);
                        str_ptr = raw_doc_get_str(val as *mut c_void)
                            as *mut u8;
                        incr_len!(str_len.wrapping_add(3)
                                      .wrapping_add(if no_indent {
                                          0
                                      } else {
                                          level.wrapping_mul(4)
                                      }), 'fail);
                        cur = emit_indent(cur, if no_indent { 0 } else { level },
                                           spaces);
                        cur = emit_raw(cur, str_ptr, str_len);
                        *cur = b',';
                        cur = cur.add(1);
                        *cur = b'\n';
                        cur = cur.add(1);
                        state = S_VAL_END;
                        continue;
                    }
                    /* goto fail_type */
                    fail_code = YYJSON_WRITE_ERROR_INVALID_VALUE_TYPE;
                    fail_msg = MSG_ERR_TYPE;
                    break 'fail;
                }
                if state == S_VAL_END {
                    /* val_end: */
                    val = val.add(1);
                    ctn_len = ctn_len.wrapping_sub(1);
                    if ctn_len == 0 {
                        state = S_CTN_END;
                        continue;
                    }
                    state = S_VAL_BEGIN;
                    continue;
                }
                /* ctn_end: */
                cur = cur.sub(2);
                *cur = b'\n';
                cur = cur.add(1);
                incr_len!(level.wrapping_mul(4), 'fail);
                level = level.wrapping_sub(1);
                cur = emit_indent(cur, level, spaces);
                *cur = b']' | ((ctn_obj as u8) << 5);
                cur = cur.add(1);
                if ctx as *mut u8 >= end {
                    break; /* goto doc_end */
                }
                yyjson_write_ctx_get(ctx, &raw mut ctn_len,
                                     &raw mut ctn_obj);
                ctx = ctx.add(1);
                ctn_len = ctn_len.wrapping_sub(1);
                *cur = b',';
                cur = cur.add(1);
                *cur = b'\n';
                cur = cur.add(1);
                if ctn_len > 0 {
                    state = S_VAL_BEGIN;
                } else {
                    state = S_CTN_END;
                }
                continue;
            }

            /* doc_end: */
            if newline {
                incr_len!(2, 'fail);
                *cur = b'\n';
                cur = cur.add(1);
            }
            *cur = b'\0';
            *dat_len = cur.offset_from(hdr) as usize;
            ffi::memset(err as *mut c_void, 0,
                        core::mem::size_of::<yyjson_write_err>());
            return hdr;
        }

        /* return_err(_code, _msg) */
        *dat_len = 0;
        (*err).code = fail_code;
        (*err).msg = fail_msg;
        if !hdr.is_null() {
            (alc.free.unwrap_unchecked())(alc.ctx, hdr as *mut c_void);
        }
        ptr::null_mut()
    }
}

#[inline]
pub(crate) unsafe fn emit_root(val: *mut yyjson_val,
                                flg: yyjson_write_flag,
                                alc_ptr: *mut yyjson_alc,
                                buf: *mut u8,
                                dat_len: *mut usize,
                                err: *mut yyjson_write_err) -> *mut c_char {
    unsafe {
        let mut tmp_err = yyjson_write_err { code: 0, msg: ptr::null() };
        let mut tmp_dat_len: usize = 0;
        let alc: yyjson_alc = if !alc_ptr.is_null() {
            *alc_ptr
        } else {
            YYJSON_DEFAULT_ALC
        };
        let root: *mut yyjson_val = val;

        let mut err = err;
        let mut dat_len = dat_len;
        if err.is_null() {
            err = &raw mut tmp_err;
        }
        if dat_len.is_null() {
            dat_len = &raw mut tmp_dat_len;
        }

        if root.is_null() {
            *dat_len = 0;
            (*err).msg = c"input JSON is NULL".as_ptr();
            (*err).code = YYJSON_READ_ERROR_INVALID_PARAMETER;
            return ptr::null_mut();
        }

        if !raw_doc_is_ctn(root as *mut c_void)
            || raw_doc_get_span(root as *mut c_void) == 0 {
            emit_root_single(root, flg, alc, buf, dat_len, err) as *mut c_char
        } else if (flg & (YYJSON_WRITE_PRETTY | YYJSON_WRITE_PRETTY_TWO_SPACES))
            != 0 {
            emit_root_pretty(root, flg, alc, buf, dat_len, err) as *mut c_char
        } else {
            emit_root_minify(root, flg, alc, buf, dat_len, err) as *mut c_char
        }
    }
}


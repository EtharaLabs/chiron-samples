/** Write raw string. */
#[inline(always)]
pub(crate) unsafe fn emit_raw(cur: *mut u8, raw: *mut u8, raw_len: usize)
    -> *mut u8 {
    unsafe {
        ffi::memcpy(cur as *mut c_void, raw as *const c_void, raw_len);
        cur.add(raw_len)
    }
}

/**
 Write string no-escape.
 @param cur Buffer cursor.
 @param str A UTF-8 string, null-terminator is not required.
 @param str_len Length of string in bytes.
 @return The buffer cursor after string.
 */
#[inline(always)]
pub(crate) unsafe fn emit_str_noesc(cur: *mut u8, str_: *mut u8,
                                     str_len: usize) -> *mut u8 {
    unsafe {
        let mut cur = cur;
        let mut str_ = str_;
        let mut str_len = str_len;
        *cur = b'"';
        cur = cur.add(1);
        while str_len >= 16 {
            copy_octets_16(cur as *mut c_void, str_ as *const c_void);
            cur = cur.add(16);
            str_ = str_.add(16);
            str_len -= 16;
        }
        while str_len >= 4 {
            copy_octets_4(cur as *mut c_void, str_ as *const c_void);
            cur = cur.add(4);
            str_ = str_.add(4);
            str_len -= 4;
        }
        while str_len != 0 {
            *cur = *str_;
            cur = cur.add(1);
            str_ = str_.add(1);
            str_len -= 1;
        }
        *cur = b'"';
        cur = cur.add(1);
        cur
    }
}

/* The `goto` targets of the error tail of `emit_str`, as an explicit state. */
const ERR_NONE: u32 = 0;
const ERR_ONE: u32 = 1;
const ERR_CPY: u32 = 2;
const ERR_ESC: u32 = 3;

/**
 Write UTF-8 string (requires len * 6 + 2 bytes buffer).
 @param cur Buffer cursor.
 @param esc Escape unicode.
 @param inv Allow invalid unicode.
 @param str A UTF-8 string, null-terminator is not required.
 @param str_len Length of string in bytes.
 @param enc_table Encode type table for character.
 @return The buffer cursor after string, or NULL on invalid unicode.
 */
#[inline(always)]
pub(crate) unsafe fn emit_str(cur: *mut u8, esc: bool, inv: bool,
                               str_: *mut u8, str_len: usize,
                               enc_table: *const char_enc_type,
                               hex_table: *const u8) -> *mut u8 {
    unsafe {
        /* The replacement character U+FFFD, used to indicate invalid
           character. Looked up via hex_table so that LOWERCASE_HEX produces
           "fffd" while the default produces "FFFD". */
        let pre = v32 { c: [b'\\', b'u', b'0', b'0'] };

        let mut src: *mut u8 = str_;
        let end: *mut u8 = str_.add(str_len);
        let mut cur = cur;
        *cur = b'"';
        cur = cur.add(1);

        /* `goto copy_ascii` is `continue 'copy_ascii`. */
        'copy_ascii: loop {
            /*
             Copy continuous ASCII, loop unrolling, same as the following code:

                 while (end > src) (
                    if (unlikely(enc_table[*src])) break;
                    *cur++ = *src++;
                 );
             */
            let stop: usize;

            /* #define expr_jump(i) \
                   if (unlikely(enc_table[src[i]])) goto stop_char_##i;
               #define expr_stop(i) \
                   stop_char_##i: memcpy(cur, src, i); \
                   cur += i; src += i; goto copy_utf8;
               The 16 `stop_char_i` labels only differ in the constant, so the
               jump records it in `stop` and the shared tail below performs the
               `expr_stop` body. */
            macro_rules! expr_jump {
                ($i:expr, $lbl:lifetime) => {
                    if *enc_table.add(*src.add($i) as usize) != 0 {
                        stop = $i;
                        break $lbl;
                    }
                };
            }

            'stop_char: {
                while (end as usize).wrapping_sub(src as usize) >= 16 {
                    /* repeat16_incr(expr_jump) */
                    expr_jump!(0, 'stop_char);
                    expr_jump!(1, 'stop_char);
                    expr_jump!(2, 'stop_char);
                    expr_jump!(3, 'stop_char);
                    expr_jump!(4, 'stop_char);
                    expr_jump!(5, 'stop_char);
                    expr_jump!(6, 'stop_char);
                    expr_jump!(7, 'stop_char);
                    expr_jump!(8, 'stop_char);
                    expr_jump!(9, 'stop_char);
                    expr_jump!(10, 'stop_char);
                    expr_jump!(11, 'stop_char);
                    expr_jump!(12, 'stop_char);
                    expr_jump!(13, 'stop_char);
                    expr_jump!(14, 'stop_char);
                    expr_jump!(15, 'stop_char);
                    copy_octets_16(cur as *mut c_void, src as *const c_void);
                    cur = cur.add(16);
                    src = src.add(16);
                }

                while (end as usize).wrapping_sub(src as usize) >= 4 {
                    /* repeat4_incr(expr_jump) */
                    expr_jump!(0, 'stop_char);
                    expr_jump!(1, 'stop_char);
                    expr_jump!(2, 'stop_char);
                    expr_jump!(3, 'stop_char);
                    copy_octets_4(cur as *mut c_void, src as *const c_void);
                    cur = cur.add(4);
                    src = src.add(4);
                }

                while end > src {
                    expr_jump!(0, 'stop_char);
                    *cur = *src;
                    cur = cur.add(1);
                    src = src.add(1);
                }

                *cur = b'"';
                cur = cur.add(1);
                return cur;
            }

            /* stop_char_##stop: */
            ptr::copy_nonoverlapping(src, cur, stop);
            cur = cur.add(stop);
            src = src.add(stop);
            /* goto copy_utf8 */

            'copy_utf8: loop {
                let mut e: u32;
                'err: {
                    if (src as usize).wrapping_add(4) > end as usize {
                        if end == src {
                            /* copy_end: */
                            *cur = b'"';
                            cur = cur.add(1);
                            return cur;
                        }
                        if (end as usize).wrapping_sub(src as usize)
                            < (*enc_table.add(*src as usize) / 2) as usize {
                            e = ERR_ONE;
                            break 'err;
                        }
                    }
                    match *enc_table.add(*src as usize) {
                        CHAR_ENC_CPY_1 => {
                            *cur = *src;
                            cur = cur.add(1);
                            src = src.add(1);
                            continue 'copy_ascii;
                        }
                        CHAR_ENC_CPY_2 => {
                            let mut uni: u32 = 0;
                            copy_octets_2((&raw mut uni) as *mut c_void,
                                        src as *const c_void);
                            if !has_utf8_seq2(uni) {
                                e = ERR_CPY;
                                break 'err;
                            }
                            copy_octets_2(cur as *mut c_void,
                                        (&raw const uni) as *const c_void);
                            cur = cur.add(2);
                            src = src.add(2);
                            continue 'copy_utf8;
                        }
                        CHAR_ENC_CPY_3 => {
                            let uni: u32;
                            if (src as usize).wrapping_add(4) <= end as usize {
                                uni = load_octets_4(src as *const c_void);
                                if !has_utf8_seq3(uni) {
                                    e = ERR_CPY;
                                    break 'err;
                                }
                                copy_octets_4(cur as *mut c_void,
                                            src as *const c_void);
                            } else {
                                uni = load_octets_3(src as *const c_void);
                                if !has_utf8_seq3(uni) {
                                    e = ERR_CPY;
                                    break 'err;
                                }
                                copy_octets_4(cur as *mut c_void,
                                            (&raw const uni) as *const c_void);
                            }
                            cur = cur.add(3);
                            src = src.add(3);
                            continue 'copy_utf8;
                        }
                        CHAR_ENC_CPY_4 => {
                            let uni: u32 = load_octets_4(src as *const c_void);
                            if !has_utf8_seq4(uni) {
                                e = ERR_CPY;
                                break 'err;
                            }
                            copy_octets_4(cur as *mut c_void,
                                        src as *const c_void);
                            cur = cur.add(4);
                            src = src.add(4);
                            continue 'copy_utf8;
                        }
                        CHAR_ENC_ESC_A => {
                            copy_octets_2(cur as *mut c_void,
                                        esc_single_char_table.0.as_ptr()
                                            .add((*src as usize) * 2)
                                            as *const c_void);
                            cur = cur.add(2);
                            src = src.add(1);
                            continue 'copy_utf8;
                        }
                        CHAR_ENC_ESC_1 => {
                            copy_octets_4(cur.add(0) as *mut c_void,
                                        (&raw const pre) as *const c_void);
                            copy_octets_2(cur.add(4) as *mut c_void,
                                        hex_table.add((*src as usize) * 2)
                                            as *const c_void);
                            cur = cur.add(6);
                            src = src.add(1);
                            continue 'copy_utf8;
                        }
                        CHAR_ENC_ESC_2 => {
                            let u: u16;
                            let mut v4: u32 = 0;
                            let v2: u16 = load_octets_2(src as *const c_void);
                            copy_octets_2((&raw mut v4) as *mut c_void,
                                        (&raw const v2) as *const c_void);
                            if !has_utf8_seq2(v4) {
                                e = ERR_ESC;
                                break 'err;
                            }
                            u = ((((*src.add(0) & 0x1F) as u16) << 6)
                                 | (((*src.add(1) & 0x3F) as u16) << 0)) as u16;
                            copy_octets_2(cur.add(0) as *mut c_void,
                                        (&raw const pre) as *const c_void);
                            copy_octets_2(cur.add(2) as *mut c_void,
                                        hex_table.add(((u >> 8) as usize) * 2)
                                            as *const c_void);
                            copy_octets_2(cur.add(4) as *mut c_void,
                                        hex_table.add(((u & 0xFF) as usize) * 2)
                                            as *const c_void);
                            cur = cur.add(6);
                            src = src.add(2);
                            continue 'copy_utf8;
                        }
                        CHAR_ENC_ESC_3 => {
                            let u: u16;
                            let v: u32 = load_octets_3(src as *const c_void);
                            if !has_utf8_seq3(v) {
                                e = ERR_ESC;
                                break 'err;
                            }
                            u = ((((*src.add(0) & 0x0F) as u16) << 12)
                                 | (((*src.add(1) & 0x3F) as u16) << 6)
                                 | (((*src.add(2) & 0x3F) as u16) << 0)) as u16;
                            copy_octets_2(cur.add(0) as *mut c_void,
                                        (&raw const pre) as *const c_void);
                            copy_octets_2(cur.add(2) as *mut c_void,
                                        hex_table.add(((u >> 8) as usize) * 2)
                                            as *const c_void);
                            copy_octets_2(cur.add(4) as *mut c_void,
                                        hex_table.add(((u & 0xFF) as usize) * 2)
                                            as *const c_void);
                            cur = cur.add(6);
                            src = src.add(3);
                            continue 'copy_utf8;
                        }
                        CHAR_ENC_ESC_4 => {
                            let hi: u32;
                            let lo: u32;
                            let mut u: u32;
                            let v: u32 = load_octets_4(src as *const c_void);
                            if !has_utf8_seq4(v) {
                                e = ERR_ESC;
                                break 'err;
                            }
                            u = (((*src.add(0) & 0x07) as u32) << 18)
                                | (((*src.add(1) & 0x3F) as u32) << 12)
                                | (((*src.add(2) & 0x3F) as u32) << 6)
                                | (((*src.add(3) & 0x3F) as u32) << 0);
                            u = u.wrapping_sub(0x10000);
                            hi = (u >> 10).wrapping_add(0xD800);
                            lo = (u & 0x3FF).wrapping_add(0xDC00);
                            copy_octets_2(cur.add(0) as *mut c_void,
                                        (&raw const pre) as *const c_void);
                            copy_octets_2(cur.add(2) as *mut c_void,
                                        hex_table.add(((hi >> 8) as usize) * 2)
                                            as *const c_void);
                            copy_octets_2(cur.add(4) as *mut c_void,
                                        hex_table
                                            .add(((hi & 0xFF) as usize) * 2)
                                            as *const c_void);
                            copy_octets_2(cur.add(6) as *mut c_void,
                                        (&raw const pre) as *const c_void);
                            copy_octets_2(cur.add(8) as *mut c_void,
                                        hex_table.add(((lo >> 8) as usize) * 2)
                                            as *const c_void);
                            copy_octets_2(cur.add(10) as *mut c_void,
                                        hex_table
                                            .add(((lo & 0xFF) as usize) * 2)
                                            as *const c_void);
                            cur = cur.add(12);
                            src = src.add(4);
                            continue 'copy_utf8;
                        }
                        CHAR_ENC_ERR_1 => {
                            e = ERR_ONE;
                            break 'err;
                        }
                        _ => {} /* default: break; unreachable */
                    }
                    /* copy_end: */
                    *cur = b'"';
                    cur = cur.add(1);
                    return cur;
                }

                /* err_one: */
                if e == ERR_ONE {
                    e = if esc { ERR_ESC } else { ERR_CPY };
                }
                if e == ERR_CPY {
                    /* err_cpy: */
                    if !inv {
                        return ptr::null_mut();
                    }
                    *cur = *src;
                    cur = cur.add(1);
                    src = src.add(1);
                    continue 'copy_utf8;
                }
                /* err_esc: */
                if !inv {
                    return ptr::null_mut();
                }
                copy_octets_2(cur.add(0) as *mut c_void,
                            (&raw const pre) as *const c_void);
                /* U+FFFD = 0xFFFD, written as two pairs from hex_table so that
                   LOWERCASE_HEX produces "fffd". Replaces a single copy_octets_4
                   from a hardcoded uppercase "FFFD" v32; same total output, one
                   extra load on the (rare) invalid-UTF-8-with-ALLOW path. */
                copy_octets_2(cur.add(2) as *mut c_void,
                            hex_table.add(0xFF * 2) as *const c_void);
                copy_octets_2(cur.add(4) as *mut c_void,
                            hex_table.add(0xFD * 2) as *const c_void);
                cur = cur.add(6);
                src = src.add(1);
                continue 'copy_utf8;
            }
        }
    }
}


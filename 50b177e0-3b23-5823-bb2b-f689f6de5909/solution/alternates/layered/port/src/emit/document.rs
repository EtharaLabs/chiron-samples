/** Write null (requires 8 bytes buffer). */
#[inline(always)]
pub(crate) unsafe fn emit_null(cur: *mut u8) -> *mut u8 {
    unsafe {
        let v = crate::support::octets::v64 { c: [b'n', b'u', b'l', b'l', b',', b'\n',
                                       0, 0] };
        copy_octets_8(cur as *mut c_void, (&raw const v) as *const c_void);
        cur.add(4)
    }
}

/** Write bool (requires 8 bytes buffer). */
#[inline(always)]
pub(crate) unsafe fn emit_bool(cur: *mut u8, val: bool) -> *mut u8 {
    unsafe {
        let v0 = crate::support::octets::v64 { c: [b'f', b'a', b'l', b's', b'e', b',',
                                        b'\n', 0] };
        let v1 = crate::support::octets::v64 { c: [b't', b'r', b'u', b'e', b',', b'\n',
                                        0, 0] };
        if val {
            copy_octets_8(cur as *mut c_void, (&raw const v1) as *const c_void);
        } else {
            copy_octets_8(cur as *mut c_void, (&raw const v0) as *const c_void);
        }
        cur.add(5 - val as usize)
    }
}

/** Write indent (requires level x 4 bytes buffer).
    Param spaces should not larger than 4. */
#[inline(always)]
pub(crate) unsafe fn emit_indent(cur: *mut u8, level: usize, spaces: usize)
    -> *mut u8 {
    unsafe {
        let mut cur = cur;
        let mut level = level;
        loop {
            let l = level;
            level = level.wrapping_sub(1);
            if !(l > 0) {
                break;
            }
            copy_octets_4(cur as *mut c_void,
                        b"    ".as_ptr() as *const c_void);
            cur = cur.add(spaces);
        }
        cur
    }
}

/** Write data to file pointer. */
#[inline]
pub(crate) unsafe fn emit_dat_to_fp(fp: *mut FILE, dat: *mut u8, len: usize,
                                     err: *mut yyjson_write_err) -> bool {
    unsafe {
        if ffi::fwrite(dat as *const c_void, 1, len, fp) != len {
            (*err).msg = c"file writing failed".as_ptr();
            (*err).code = YYJSON_WRITE_ERROR_FILE_WRITE;
            return false;
        }
        true
    }
}

/** Write data to file. */
#[inline]
pub(crate) unsafe fn emit_dat_to_file(path: *const c_char, dat: *mut u8,
                                       len: usize,
                                       err: *mut yyjson_write_err) -> bool {
    unsafe {
        /* #define return_err(_code, _msg) do { \
               err->msg = _msg; \
               err->code = YYJSON_WRITE_ERROR_##_code; \
               if (file) fclose(file); \
               return false; \
           } while (false) */
        let mut file: *mut FILE = fopen_writeonly(path);
        if file.is_null() {
            /* return_err(FILE_OPEN, MSG_FOPEN) */
            (*err).msg = MSG_FOPEN;
            (*err).code = YYJSON_WRITE_ERROR_FILE_OPEN;
            if !file.is_null() {
                ffi::fclose(file);
            }
            return false;
        }
        if ffi::fwrite(dat as *const c_void, 1, len, file) != len {
            /* return_err(FILE_WRITE, MSG_FWRITE) */
            (*err).msg = MSG_FWRITE;
            (*err).code = YYJSON_WRITE_ERROR_FILE_WRITE;
            if !file.is_null() {
                ffi::fclose(file);
            }
            return false;
        }
        if ffi::fclose(file) != 0 {
            file = ptr::null_mut();
            /* return_err(FILE_WRITE, MSG_FCLOSE) */
            (*err).msg = MSG_FCLOSE;
            (*err).code = YYJSON_WRITE_ERROR_FILE_WRITE;
            if !file.is_null() {
                ffi::fclose(file);
            }
            return false;
        }
        true
    }
}


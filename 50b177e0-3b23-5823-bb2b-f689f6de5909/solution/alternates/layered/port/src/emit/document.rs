const _: () = assert!(core::mem::size_of::<yyjson_mut_write_ctx>() == 16);

#[inline(always)]
pub(crate) unsafe fn yyjson_mut_write_ctx_set(ctx: *mut yyjson_mut_write_ctx,
                                              ctn: *mut yyjson_mut_val,
                                              size: usize, is_obj: bool) {
    unsafe {
        (*ctx).tag = size.wrapping_shl(1) | (is_obj as usize);
        (*ctx).ctn = ctn;
    }
}

#[inline(always)]
pub(crate) unsafe fn yyjson_mut_write_ctx_get(ctx: *mut yyjson_mut_write_ctx,
                                              ctn: *mut *mut yyjson_mut_val,
                                              size: *mut usize,
                                              is_obj: *mut bool) {
    unsafe {
        let tag: usize = (*ctx).tag;
        *size = tag >> 1;
        *is_obj = (tag & 1) != 0;
        *ctn = (*ctx).ctn;
    }
}

/** Get the estimated number of values for the mutable JSON document. */
#[inline(always)]
pub(crate) unsafe fn yyjson_mut_doc_estimated_val_num(doc: *mut yyjson_mut_doc)
    -> usize {
    unsafe {
        let mut sum: usize = 0;
        let mut chunk: *mut yyjson_val_chunk = (*doc).val_pool.chunks;
        while !chunk.is_null() {
            sum = sum.wrapping_add(
                ((*chunk).chunk_size
                     / core::mem::size_of::<yyjson_mut_val>())
                    .wrapping_sub(1));
            if chunk == (*doc).val_pool.chunks {
                sum = sum.wrapping_sub(
                    (*doc).val_pool.end.offset_from((*doc).val_pool.cur)
                        as usize);
            }
            chunk = (*chunk).next;
        }
        sum
    }
}


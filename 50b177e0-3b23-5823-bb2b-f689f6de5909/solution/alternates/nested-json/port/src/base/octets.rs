/** Loads 2 bytes from `src` as a u16 (native-endian). */
#[inline(always)]
pub(crate) unsafe fn mem_fetch_2(src: *const c_void) -> u16 {
    unsafe { core::ptr::read_unaligned(src as *const u16) }
}

/** Loads 3 bytes from `src` as a u32 (native-endian).
    The C code copies 2 bytes into the union, then sets byte 2 from `src` and
    byte 3 to 0, which on little-endian yields `src[0] | src[1]<<8 | src[2]<<16`.
    Reproduced here through the same union so the byte order is identical on
    either endianness. */
#[inline(always)]
pub(crate) unsafe fn mem_fetch_3(src: *const c_void) -> u32 {
    unsafe {
        let mut uni = v32_uni { u: 0 };
        core::ptr::copy_nonoverlapping(src as *const u8,
                                       (&raw mut uni) as *mut u8, 2);
        uni.v.c[2] = *(src as *const u8).add(2);
        uni.v.c[3] = 0;
        uni.u
    }
}

/** Loads 4 bytes from `src` as a u32 (native-endian). */
#[inline(always)]
pub(crate) unsafe fn mem_fetch_4(src: *const c_void) -> u32 {
    unsafe { core::ptr::read_unaligned(src as *const u32) }
}


/** Load 4 hex characters to `u16`, return true on valid input. */
#[inline(always)]
pub(crate) unsafe fn hexa_load_4(src: *mut u8, dst: *mut u16) -> bool {
    unsafe {
        let c0 = hex_conv_table[*src.add(0) as usize] as u16;
        let c1 = hex_conv_table[*src.add(1) as usize] as u16;
        let c2 = hex_conv_table[*src.add(2) as usize] as u16;
        let c3 = hex_conv_table[*src.add(3) as usize] as u16;
        let t0 = (c0 << 8) | c2;
        let t1 = (c1 << 8) | c3;
        *dst = (t0 << 4) | t1;
        ((t0 | t1) & 0xF0F0u16) == 0
    }
}

/** Load 2 hex characters to `u8`, return true on valid input. */
#[inline(always)]
pub(crate) unsafe fn hexa_load_2(src: *mut u8, dst: *mut u8) -> bool {
    unsafe {
        let c0 = hex_conv_table[*src.add(0) as usize];
        let c1 = hex_conv_table[*src.add(1) as usize];
        *dst = (c0 << 4) | c1;
        ((c0 | c1) & 0xF0) == 0
    }
}

/** Match a hexadecimal numeric character: [0-9a-fA-F]. */
#[inline(always)]
pub(crate) unsafe fn ch_hex(c: u8) -> bool {
    hex_conv_table[c as usize] != 0xF0
}

/*==============================================================================
 * MARK: - UTF8 Validation (Private) (yyjson.c:1094-1183)
 *
 * The `utf8_seq_*` constants are the little-endian expansion of the C
 * `utf8_seq_def` token-pasting macro, generated by gen_utf8_seq.py.
 *
 * `detect_utf8_seq3`/`detect_utf8_seq4` are C macros that assign to a caller-local
 * scratch `u32 tmp`. No caller ever reads `tmp` afterwards (verified against
 * every use site in yyjson.c), so the scratch becomes a function local here
 * and the predicates are plain pure functions.
 *============================================================================*/

include!("utf8.rs");

/** 1-byte sequence (U+0000 to U+007F). */
#[inline(always)]
pub(crate) unsafe fn detect_utf8_seq1(uni: u32) -> bool {
    (uni & utf8_seq_b1_mask) == utf8_seq_b1_patt
}

/** 2-byte sequence (U+0080 to U+07FF). */
#[inline(always)]
pub(crate) unsafe fn detect_utf8_seq2(uni: u32) -> bool {
    (uni & utf8_seq_b2_mask) == utf8_seq_b2_patt && (uni & utf8_seq_b2_requ) != 0
}

/** 3-byte sequence (U+0800 to U+FFFF), surrogate halves rejected. */
#[inline(always)]
pub(crate) unsafe fn detect_utf8_seq3(uni: u32) -> bool {
    let tmp: u32;
    (uni & utf8_seq_b3_mask) == utf8_seq_b3_patt
        && {
            tmp = uni & utf8_seq_b3_requ;
            tmp != 0
        }
        && tmp != utf8_seq_b3_erro
}

/** 4-byte sequence (U+10000 to U+10FFFF). */
#[inline(always)]
pub(crate) unsafe fn detect_utf8_seq4(uni: u32) -> bool {
    let tmp: u32;
    (uni & utf8_seq_b4_mask) == utf8_seq_b4_patt
        && {
            tmp = uni & utf8_seq_b4_requ;
            tmp != 0
        }
        && ((tmp & utf8_seq_b4_req1) == 0 || (tmp & utf8_seq_b4_req2) == 0)
}


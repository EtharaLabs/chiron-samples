/** Match UTF-8 byte order mask. */
#[inline(always)]
pub(crate) unsafe fn detect_utf8_bom(cur: *mut u8) -> bool {
    unsafe {
        mem_fetch_3(cur as *const c_void)
            == mem_fetch_3(c"\xEF\xBB\xBF".as_ptr() as *const c_void)
    }
}

/** Match UTF-16 byte order mask. */
#[inline(always)]
pub(crate) unsafe fn detect_utf16_bom(cur: *mut u8) -> bool {
    unsafe {
        mem_fetch_2(cur as *const c_void)
            == mem_fetch_2(c"\xFE\xFF".as_ptr() as *const c_void)
            || mem_fetch_2(cur as *const c_void)
                == mem_fetch_2(c"\xFF\xFE".as_ptr() as *const c_void)
    }
}

/** Match UTF-32 byte order mask, need length check to avoid zero padding.
    The C patterns are the 4-byte literals "\x00\x00\xFE\xFF" and
    "\xFF\xFE\x00\x00"; embedded NULs make a `c"..."` literal unusable here, so
    the two patterns are spelled as byte arrays with the trailing NUL the C
    string literal also has. */
#[inline(always)]
pub(crate) unsafe fn detect_utf32_bom(cur: *mut u8) -> bool {
    const BE: [u8; 5] = [0x00, 0x00, 0xFE, 0xFF, 0x00];
    const LE: [u8; 5] = [0xFF, 0xFE, 0x00, 0x00, 0x00];
    unsafe {
        mem_fetch_4(cur as *const c_void)
            == mem_fetch_4(BE.as_ptr() as *const c_void)
            || mem_fetch_4(cur as *const c_void)
                == mem_fetch_4(LE.as_ptr() as *const c_void)
    }
}

/** Get the extended line end length. Used with `ch_eol_ext`. */
#[inline(always)]
pub(crate) unsafe fn local_ext_eol_len(cur: *mut u8) -> usize {
    unsafe {
        if *cur.add(0) < 0x80 {
            return 1;
        }
        if *cur.add(1) == 0x80
            && (*cur.add(2) == 0xA8 || *cur.add(2) == 0xA9)
        {
            return 3;
        }
        0
    }
}

/** Get the extended whitespace length. Used with `ch_space_ext`. */
#[inline(always)]
pub(crate) unsafe fn local_ext_space_len(cur: *mut u8) -> usize {
    unsafe {
        if *cur.add(0) < 0x80 {
            return 1;
        } else if mem_fetch_2(cur as *const c_void)
            == mem_fetch_2(c"\xC2\xA0".as_ptr() as *const c_void)
        {
            return 2;
        } else if mem_fetch_2(cur as *const c_void)
            == mem_fetch_2(c"\xE2\x80".as_ptr() as *const c_void)
        {
            if *cur.add(2) >= 0x80 && *cur.add(2) <= 0x8A {
                return 3;
            }
            if *cur.add(2) == 0xA8 || *cur.add(2) == 0xA9
                || *cur.add(2) == 0xAF
            {
                return 3;
            }
        } else {
            let uni = mem_fetch_3(cur as *const c_void);
            if uni == mem_fetch_3(c"\xE1\x9A\x80".as_ptr() as *const c_void)
                || uni == mem_fetch_3(c"\xE2\x81\x9F".as_ptr() as *const c_void)
                || uni == mem_fetch_3(c"\xE3\x80\x80".as_ptr() as *const c_void)
                || uni == mem_fetch_3(c"\xEF\xBB\xBF".as_ptr() as *const c_void)
            {
                return 3;
            }
        }
        0
    }
}


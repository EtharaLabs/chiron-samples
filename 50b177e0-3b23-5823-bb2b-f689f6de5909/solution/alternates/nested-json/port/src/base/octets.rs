/** Same as `memmove(dst, src, 16)`, allows overlap. */
#[inline(always)]
pub(crate) unsafe fn mem_shift_16(dst: *mut c_void, src: *const c_void) {
    unsafe {
        let pdst = dst as *mut u8;
        let psrc = src as *const u8;
        let tmp1: u64 = core::ptr::read_unaligned(psrc as *const u64);
        let tmp2: u64 = core::ptr::read_unaligned(psrc.add(8) as *const u64);
        core::ptr::write_unaligned(pdst as *mut u64, tmp1);
        core::ptr::write_unaligned(pdst.add(8) as *mut u64, tmp2);
    }
}

/** Same as `memmove(dst, src, n)`, but only `dst <= src` and `n <= 16`. */
#[inline(always)]
pub(crate) unsafe fn mem_shift_forward(dst: *mut c_void, src: *mut c_void,
                                       n: usize) {
    unsafe {
        let mut d = dst as *mut u8;
        let mut s = src as *mut u8;
        let mut n = n;
        n += n % 2; /* round up to even */
        if n == 16 {
            mem_shift_16(d as *mut c_void, s as *const c_void);
            return;
        }
        if n >= 8 {
            mem_shift_8(d as *mut c_void, s as *const c_void);
            n -= 8;
            d = d.add(8);
            s = s.add(8);
        }
        if n >= 4 {
            mem_shift_4(d as *mut c_void, s as *const c_void);
            n -= 4;
            d = d.add(4);
            s = s.add(4);
        }
        if n >= 2 {
            mem_shift_2(d as *mut c_void, s as *const c_void);
        }
    }
}

/** Same as `memcmp(buf, pat, 2) == 0`. */
#[inline(always)]
pub(crate) unsafe fn mem_match_2(buf: *mut c_void, pat: *const u8) -> bool {
    unsafe {
        let u1: u16 = core::ptr::read_unaligned(buf as *const u16);
        let u2: u16 = core::ptr::read_unaligned(pat as *const u16);
        u1 == u2
    }
}


/** yyjson.c:7624  Convert f32 from binary to decimal (shortest but may have
    trailing zeros). The input should not be 0, inf or nan. */
#[inline(always)]
pub(crate) unsafe fn f32_bin_to_dec(sig_raw: u32, exp_raw: u32, sig_bin: u32,
                                    exp_bin: i32, sig_dec: *mut u32,
                                    exp_dec: *mut i32) {
    unsafe {
        let is_even: bool;
        let irregular: bool;
        let round_up: bool;
        let trim: bool;
        let mut u0_inside: bool;
        let u1_inside: bool;
        let mut w0_inside: bool;
        let mut w1_inside: bool;
        let mut p10_hi: u64 = 0;
        let mut p10_lo: u64 = 0;
        let mut hi: u64 = 0;
        let mut lo: u64 = 0;
        let s: u32;
        let sp: u32;
        let mut cb: u32;
        let cbl: u32;
        let cbr: u32;
        let vb: u32;
        let vbl: u32;
        let vbr: u32;
        let upper: u32;
        let lower: u32;
        let mid: u32;
        let mut k: i32;
        let mut h: i32;

        /* Fast path, see f64_bin_to_dec(). */
        'fast: {
            if sig_raw != 0 {
                let mod_: u32;
                let dec: u32;
                let add_1: u32;
                let add_10: u32;
                let s_hi: u32;
                let s_lo: u32;
                let c: u32;
                let half_ulp: u32;
                let t0: u32;
                let t1: u32;

                /* k = floor(exp_bin * log10(2)); */
                /* h = exp_bin + floor(log2(10) * -k); (h = 0/1/2/3) */
                k = exp_bin.wrapping_mul(315653) >> 20;
                h = exp_bin.wrapping_add(
                    (k.wrapping_neg().wrapping_mul(217707)) >> 16);
                pow10_table_get_sig(k.wrapping_neg(), &mut p10_hi, &mut p10_lo);

                /* sig_bin << (1/2/3/4) */
                cb = sig_bin.wrapping_shl((h + 1) as u32);
                u128_mul(cb as u64, p10_hi, &mut hi, &mut lo);
                s_hi = hi as u32;
                s_lo = (lo >> 32) as u32;
                mod_ = s_hi % 10;
                dec = s_hi.wrapping_sub(mod_);

                /* right shift 4 to fit in u32 */
                c = (mod_.wrapping_shl(32 - 4)) | (s_lo >> 4);
                half_ulp = (p10_hi >> (32 + 4 - h)) as u32;

                /* check w1, u0, w0 range */
                w1_inside = s_lo >= (1u32 << 31);
                if s_lo == (1u32 << 31) {
                    break 'fast;
                }
                u0_inside = half_ulp >= c;
                if half_ulp == c {
                    break 'fast;
                }
                t0 = 10u32 << (32 - 4);
                t1 = c.wrapping_add(half_ulp);
                w0_inside = t1 >= t0;
                if t0.wrapping_sub(t1) <= 1u32 {
                    break 'fast;
                }

                trim = u0_inside | w0_inside;
                add_10 = if w0_inside { 10 } else { 0 };
                add_1 = mod_.wrapping_add(w1_inside as u32);
                *sig_dec = dec
                    .wrapping_add(if trim { add_10 } else { add_1 });
                *exp_dec = k;
                return;
            }
        }

        /* Schubfach algorithm, see f64_bin_to_dec(). */
        irregular = sig_raw == 0 && exp_raw > 1;
        is_even = (sig_bin & 1) == 0;
        cbl = (4u32.wrapping_mul(sig_bin)).wrapping_sub(2)
            .wrapping_add(irregular as u32);
        cb = 4u32.wrapping_mul(sig_bin);
        cbr = (4u32.wrapping_mul(sig_bin)).wrapping_add(2);

        /* k = floor(exp_bin * log10(2) + (irregular ? log10(3.0 / 4.0) : 0)); */
        /* h = exp_bin + floor(log2(10) * -k) + 1; (h = 1/2/3/4) */
        k = (exp_bin.wrapping_mul(315653)
            .wrapping_sub(if irregular { 131237 } else { 0 })) >> 20;
        h = exp_bin.wrapping_add(
            (k.wrapping_neg().wrapping_mul(217707)) >> 16).wrapping_add(1);
        pow10_table_get_sig(k.wrapping_neg(), &mut p10_hi, &mut p10_lo);
        p10_hi = p10_hi.wrapping_add(1);

        vbl = u64_round_to_odd(p10_hi, cbl.wrapping_shl(h as u32));
        vb = u64_round_to_odd(p10_hi, cb.wrapping_shl(h as u32));
        vbr = u64_round_to_odd(p10_hi, cbr.wrapping_shl(h as u32));
        lower = vbl.wrapping_add((!is_even) as u32);
        upper = vbr.wrapping_sub((!is_even) as u32);

        s = vb / 4;
        if s >= 10 {
            sp = s / 10;
            u0_inside = lower <= 40u32.wrapping_mul(sp);
            w0_inside = upper >= (40u32.wrapping_mul(sp)).wrapping_add(40);
            if u0_inside != w0_inside {
                *sig_dec = (sp.wrapping_mul(10))
                    .wrapping_add(if w0_inside { 10 } else { 0 });
                *exp_dec = k;
                return;
            }
        }
        u1_inside = lower <= 4u32.wrapping_mul(s);
        w1_inside = upper >= (4u32.wrapping_mul(s)).wrapping_add(4);
        mid = (4u32.wrapping_mul(s)).wrapping_add(2);
        round_up = (vb > mid) || (vb == mid && (s & 1) != 0);
        *sig_dec = s.wrapping_add(if u1_inside != w1_inside {
            w1_inside as u32
        } else {
            round_up as u32
        });
        *exp_dec = k;
    }
}


#[inline(always)]
pub(crate) unsafe fn write_u64(val: u64, mut buf: *mut u8) -> *mut u8 {
    unsafe {
        if val < 100000000 {
            /* 1-8 digits */
            buf = write_u32_len_1_to_8(val as u32, buf);
            buf
        } else if val < 100000000u64 * 100000000 {
            /* 9-16 digits */
            let hgh: u64 = val / 100000000;
            let low: u32 = val.wrapping_sub(hgh.wrapping_mul(100000000)) as u32;
            buf = write_u32_len_1_to_8(hgh as u32, buf);
            buf = write_u32_len_8(low, buf);
            buf
        } else {
            /* 17-20 digits */
            let tmp: u64 = val / 100000000;
            let low: u32 = val.wrapping_sub(tmp.wrapping_mul(100000000)) as u32;
            let hgh: u64 = (tmp / 10000) as u32 as u64;
            let mid: u32 = tmp.wrapping_sub(hgh.wrapping_mul(10000)) as u32;
            buf = write_u32_len_5_to_8(hgh as u32, buf);
            buf = write_u32_len_4(mid, buf);
            buf = write_u32_len_8(low, buf);
            buf
        }
    }
}


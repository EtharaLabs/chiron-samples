        pow10_table_get_sig(k.wrapping_neg(), &mut p10_hi, &mut p10_lo);
        p10_lo = p10_lo.wrapping_add(1);

        vbl = u128_round_to_odd(p10_hi, p10_lo, cbl.wrapping_shl(h as u32));
        vb = u128_round_to_odd(p10_hi, p10_lo, cb.wrapping_shl(h as u32));
        vbr = u128_round_to_odd(p10_hi, p10_lo, cbr.wrapping_shl(h as u32));

/** yyjson.c:8414  Write a JSON number (requires 40 bytes buffer).
    Called by writer.rs. */
#[inline(never)]
pub(crate) unsafe fn write_num(cur: *mut u8, val: *mut yyjson_val,
                               flg: yyjson_write_flag) -> *mut u8 {
    unsafe {
        if ((*val).tag & YYJSON_SUBTYPE_REAL as u64) == 0 {
            let pos: u64 = (*val).uni.u64_;
            let neg: u64 = (!pos).wrapping_add(1);
            let sign: usize = ((((*val).tag & YYJSON_SUBTYPE_SINT as u64) > 0)
                & ((pos as i64) < 0)) as usize;
            *cur = b'-';
            write_u64(if sign != 0 { neg } else { pos }, cur.add(sign))
        } else {
            let raw: u64 = (*val).uni.u64_;
            let val_fmt: u32 = ((*val).tag >> 32) as u32;
            let all_fmt: u32 = flg;
            let fmt: u32 = val_fmt | all_fmt;
            if (fmt >> (32 - YYJSON_WRITE_FP_FLAG_BITS)) == 0 {
                /* double to shortest */
                write_f64_raw(cur, raw, flg)
            } else if (fmt >> (32 - YYJSON_WRITE_FP_PREC_BITS)) != 0 {
                /* double to fixed */
                let val_prec: u32 = val_fmt >> (32 - YYJSON_WRITE_FP_PREC_BITS);
                let all_prec: u32 = all_fmt >> (32 - YYJSON_WRITE_FP_PREC_BITS);
                let prec: u32 = if val_prec != 0 { val_prec } else { all_prec };
                write_f64_raw_fixed(cur, raw, flg, prec)
            } else {
                if (fmt & YYJSON_WRITE_FP_TO_FLOAT) != 0 {
                    /* float to shortest */
                    write_f32_raw(cur, raw, flg)
                } else {
                    /* double to shortest */
                    write_f64_raw(cur, raw, flg)
                }
            }
        }
    }
}


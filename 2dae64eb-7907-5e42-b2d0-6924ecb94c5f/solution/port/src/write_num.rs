/** yyjson.c:7863  Write inf/nan if allowed. */
#[inline(always)]
pub(crate) unsafe fn write_inf_or_nan(mut buf: *mut u8, flg: yyjson_write_flag,
                                      sig_raw: u64, sign: bool) -> *mut u8 {
    unsafe {
        /* has_flg(INF_AND_NAN_AS_NULL) */
        if has_wflag(flg, YYJSON_WRITE_INF_AND_NAN_AS_NULL, false) {
            byte_copy_4(buf as *mut c_void, b"null".as_ptr() as *const c_void);
            return buf.add(4);
        }
        /* has_allow(INF_AND_NAN) */
        if has_wflag(flg, YYJSON_WRITE_ALLOW_INF_AND_NAN, true) {
            if sig_raw == 0 {
                *buf.add(0) = b'-';
                buf = buf.add(sign as usize);
                byte_copy_8(buf as *mut c_void,
                            b"Infinity".as_ptr() as *const c_void);
                return buf.add(8);
            } else {
                byte_copy_4(buf as *mut c_void,
                            b"NaN\0".as_ptr() as *const c_void);
                return buf.add(3);
            }
        }
        core::ptr::null_mut()
    }
}


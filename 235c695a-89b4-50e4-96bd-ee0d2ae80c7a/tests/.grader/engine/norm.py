"""Normalization applied identically to State A recordings and to graded output.

Every rule here removes a difference that depends on where or when a run happens, never on how
the project was built: absolute scratch paths, timing figures, the log hash that covers them,
terminal colour, and the interleaving of parallel output.
"""

from __future__ import annotations

import re

from .util import strip_ansi

TIMING = [
    (re.compile(r"Logfile hash: [0-9a-f]+"), "Logfile hash: <hash>"),
    (re.compile(r"CPU: user [0-9.]+s system [0-9.]+s(, MEM: [0-9.]+ MB peak)?"), "CPU: <time>"),
    (re.compile(r"time: [0-9.]+s, user: [0-9.]+s, system: [0-9.]+s"), "time: <time>"),
    (re.compile(r"\b[0-9]+(\.[0-9]+)? (sec|seconds|ms)\b"), "<n> sec"),
    (re.compile(r"MEM: [0-9.]+ MB"), "MEM: <n> MB"),
    # ABC stamps its own compile time (__DATE__ __TIME__) into its banner.
    (re.compile(r"\(compiled [A-Z][a-z]{2} [ 0-9][0-9] [0-9]{4} [0-9]{2}:[0-9]{2}:[0-9]{2}\)"), "(compiled <date>)"),
]
DROP_LINE = [
    re.compile(r"^\s*Time spent: "),
    re.compile(r"^\s*[0-9]+% [0-9]+ calls? "),
]
# A generator that names itself in its output names the path it was invoked by, which depends on
# the build directory rather than on the generated content.
GENERATED_BY = re.compile(r"^(\s*(?://|#)\s*Generated by )\S*/([^/\s]+)$")


def normalize(text: str, subs: list[tuple[str, str]], banner: str | None = None) -> str:
    """Strip colour, replace scratch paths and timing, and hide the version banner when given."""
    text = strip_ansi(text).replace("\r\n", "\n")
    for old, new in sorted(subs, key=lambda pair: -len(pair[0])):
        if old:
            text = text.replace(old, new)
    if banner:
        text = text.replace(banner, "<banner>")
    lines = []
    for line in text.split("\n"):
        if any(rule.search(line) for rule in DROP_LINE):
            continue
        for rule, repl in TIMING:
            line = rule.sub(repl, line)
        line = GENERATED_BY.sub(r"\1\2", line)
        lines.append(line.rstrip())
    while lines and not lines[-1]:
        lines.pop()
    return "\n".join(lines)


def sorted_lines(text: str) -> str:
    """Order-insensitive form for output whose line order follows process scheduling."""
    return "\n".join(sorted(line for line in text.split("\n") if line.strip()))
